// evenly spaced waypoints along a stroke, about `step` apart
export function subdivide(points, step = 12) {
  const out = [points[0]];
  for (let i = 1; i < points.length; i++) {
    const [x1, y1] = points[i - 1], [x2, y2] = points[i];
    const d = Math.hypot(x2 - x1, y2 - y1);
    const n = Math.max(1, Math.round(d / step));
    for (let k = 1; k <= n; k++) out.push([x1 + ((x2 - x1) * k) / n, y1 + ((y2 - y1) * k) / n]);
  }
  return out;
}

// a wavy line across the middle to cut along
export function makeCutLine(rand = Math.random) {
  const phase = rand() * Math.PI * 2;
  const amp = 14 + rand() * 14;
  const pts = [];
  for (let x = 8; x <= 92; x += 6) {
    pts.push([x, 50 + amp * Math.sin(x / 14 + phase)]);
  }
  return [pts];
}
